"""Write docs/review/SKILL_ORDER.md: the teaching order of every skill, for native review.

Generated from the passage bank with learner/skills.py, so re-running after a fix keeps the sheet
in step with what placement and tracking use. Reviewers tick and annotate the generated file;
fixes go into learner/skills.py (the ticks and notes have to be copied over by hand on a re-run).

    uv run python scripts/export_skill_order.py
"""

import json
import sys
from collections import Counter
from pathlib import Path

from akshara.core.text import words
from akshara.learner.skills import STAGES, build

ROOT = Path(__file__).resolve().parent.parent
BANK = ROOT / "data" / "open_passages" / "candidates.jsonl"
OUT = ROOT / "docs" / "review" / "SKILL_ORDER.md"
LANGS = {
    "hi-IN": ("Hindi", "Achindra"),
    "kn-IN": ("Kannada", "Daniel"),
    "ta-IN": ("Tamil", "Daniel"),
}
EXAMPLES = 3


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    bank = [json.loads(x) for x in BANK.read_text(encoding="utf-8").splitlines() if x]
    out = [
        "# Skill order: native-speaker review",
        "",
        "*Generated by `scripts/export_skill_order.py`; do not edit the tables by hand. Tick each "
        "box when checked and write fixes in the notes; fixes go into "
        "`src/akshara/learner/skills.py`.*",
        "",
        "This is the order in which the tutor assumes a child learns to read each script. "
        "Placement, mastery tracking and (later) practice passages all build on it. The stages "
        "are fixed by design; inside a stage, skills are ordered by how often they appear in "
        "the 413-passage StoryWeaver bank, so the first ones unlock the most text. Nothing here "
        "was learned from children.",
        "",
        "Please check:",
        "- is the stage order right for how this script is taught in schools?",
        "- within a stage, would a teacher teach these in a very different order?",
        "- is anything missing, or is something listed that is not a real reading skill?",
        "",
        "Stages: " + " → ".join(STAGES) + ". `conjunct:other` pools the rarer conjuncts.",
        "",
    ]
    for lang, (name, who) in LANGS.items():
        texts = [r["reference"] for r in bank if r["lang"] == lang]
        cur = build(texts, lang)
        freq = Counter(w for t in texts for w in words(t))
        examples: dict[str, list[str]] = {}
        for w, _ in freq.most_common():
            for s in cur.skills_of(w):
                if len(examples.setdefault(s, [])) < EXAMPLES:
                    examples[s].append(w)
        out += [f"## {name} ({lang}) — reviewer: {who}", ""]
        out += ["| # | Stage | Skill | In the bank | Example words | OK | Notes |"]
        out += ["|---|---|---|---|---|---|---|"]
        for i, s in enumerate(cur.skills, 1):
            ex = ", ".join(examples.get(s.id, []))
            out.append(f"| {i} | {s.stage} | `{s.id}` | {s.count} | {ex} | [ ] | |")
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
