"""Write docs/review/SCRIPT_TABLES.md: the script tables and planted examples, for native review.

Everything in it is generated from code and data, so re-running after a fix keeps the sheet in step
with what the planter and (later) the sound check actually use. Reviewers tick and annotate the
generated file; fixes go into core/script.py or the build scripts, then this is re-run (the ticks
and notes have to be copied over by hand).

    uv run python scripts/export_script_review.py
"""

import json
import sys
from pathlib import Path

from akshara.core.aksharas import split
from akshara.core.plant import TAXONOMY, TYPES_V2
from akshara.core.script import (
    LANGS,
    consonants,
    independent_vowels,
    length_partner,
    sound_neighbours,
    visual_neighbours,
    vowel_signs,
)
from akshara.core.text import words

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "review" / "SCRIPT_TABLES.md"
NAMES = {"hi-IN": "Hindi", "kn-IN": "Kannada", "ta-IN": "Tamil"}
REVIEWER = {"hi-IN": "Achindra", "kn-IN": "Daniel", "ta-IN": "Daniel"}
NEW_TYPES = [t for t in TYPES_V2 if t not in ("skip", "near", "distant", "half")] + ["decode"]
SIGN_OFF = "- [ ] Reviewed by {who} on ____ · notes:\n"


def rows(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text("utf-8").splitlines() if x]


def section(lang: str, v2: list[dict], words_seen: list[str]) -> str:
    who = REVIEWER[lang]
    out = [f"## {NAMES[lang]} ({lang}) — reviewer: {who}\n"]

    out.append("### Consonants\n")
    out.append(
        "Check: the features, the close sounds (would a child or listener confuse them?), and "
        "the look-alikes (do they really look alike in print?).\n"
    )
    out.append("| Letter | Place | Manner | Voiced | Aspirated | Close sounds | Look-alikes |")
    out.append("|---|---|---|---|---|---|---|")
    for ch, c in consonants(lang).items():
        sounds = ", ".join(f"{o} ({how})" for o, how in sound_neighbours(ch, lang)) or "—"
        looks = ", ".join(f"{o} {s:.2f}" for o, s in visual_neighbours(ch, lang)[:3])
        out.append(
            f"| {ch} | {c.place} | {c.manner} | {'yes' if c.voiced else 'no'} | "
            f"{'yes' if c.aspirated else 'no'} | {sounds} | {looks} |"
        )
    out.append("\n" + SIGN_OFF.format(who=who))

    out.append("### Vowels\n")
    out.append("| Letter | Sign | Vowel | Long | Length partner |")
    out.append("|---|---|---|---|---|")
    signs = {v.quality + str(v.long): s for s, v in vowel_signs(lang).items()}
    for ch, v in independent_vowels(lang).items():
        sign = signs.get(v.quality + str(v.long), "")
        partner = length_partner(ch, lang) or "—"
        out.append(
            f"| {ch} | {('◌' + sign) if sign else '(none)'} | {v.quality} | "
            f"{'yes' if v.long else 'no'} | {partner} |"
        )
    out.append("\n" + SIGN_OFF.format(who=who))

    out.append("### Akshara splits\n")
    out.append("Check: is each word cut into the units a child is taught to read?\n")
    out.append("| Word | Aksharas |")
    out.append("|---|---|")
    for w in words_seen:
        out.append(f"| {w} | {' · '.join(split(w, lang))} |")
    out.append("\n" + SIGN_OFF.format(who=who))

    out.append("### Planted mistakes (second set)\n")
    out.append(
        "Check: is each one something a child might plausibly say? Mark implausible ones; they "
        "will be removed or the rule changed.\n"
    )
    out.append("| Type | Story word | Read as | What changed |")
    out.append("|---|---|---|---|")
    for t in NEW_TYPES:
        shown = 0
        for p in v2:
            ref = words(p["reference"])
            for e in p["errors"]:
                if e["type"] == t and shown < 3:
                    said = e.get("said", "")
                    out.append(f"| {t} | {ref[e['index']]} | {said} | {e.get('detail', '')} |")
                    shown += 1
    out.append("\n" + SIGN_OFF.format(who=who))
    return "\n".join(out)


def sample_words(lang: str, texts: list[str], n: int = 16) -> list[str]:
    """Words with conjuncts, pulli or several aksharas first, in a stable order."""
    seen = sorted({w for t in texts for w in words(t)})
    hard = [w for w in seen if any(len(a) > 2 for a in split(w, lang))]
    return (hard[:: max(1, len(hard) // n)] + seen)[:n]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    v2 = rows(ROOT / "data" / "bench" / "passages_v2.jsonl")
    cands = rows(ROOT / "data" / "open_passages" / "candidates.jsonl")
    head = [
        "# Script tables: native-speaker review\n",
        "*Generated by `scripts/export_script_review.py`; do not edit the tables by hand. Tick each"
        " box when checked and write fixes in the notes; fixes go into "
        "`src/akshara/core/script.py` or the build scripts.*\n",
        "These tables decide which mistakes are planted in the benchmark and, later, which "
        "alternatives the per-word sound check compares against. Nothing here was learned from "
        "data: features come from the traditional letter grid, look-alikes from rendered glyphs "
        "(`scripts/build_glyph_table.py`, three fonts per script). That is why a native check "
        "is required before results built on them are published.\n",
        "Mistake types and how they are scored:\n",
        '| Type | Family | Should be flagged | "Not sure" acceptable | Audible when synthesised |',
        "|---|---|---|---|---|",
        *[
            f"| {t} | {k.family} | {'yes' if k.should_flag else 'no'} | "
            f"{'yes' if k.abstain_ok else 'no'} | {k.audible} |"
            for t, k in TAXONOMY.items()
        ],
        "",
    ]
    body = [
        section(
            lang,
            [p for p in v2 if p["lang"] == lang],
            sample_words(lang, [c["reference"] for c in cands if c["lang"] == lang]),
        )
        for lang in LANGS
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(head) + "\n" + "\n\n".join(body) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
